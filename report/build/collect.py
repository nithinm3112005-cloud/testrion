def col_info(df, target):
    out = []
    for c in df.columns:
        s = df[c]; num = pd.api.types.is_numeric_dtype(s)
        row = {"name": c, "type": "numeric" if num else "categorical", "unique": int(s.nunique()), "missing": int(s.isna().sum()),
               "target": c == target}
        if num:
            row.update(min=float(s.min()), max=float(s.max()), mean=float(s.mean()), median=float(s.median()))
        else:
            vc = s.value_counts().head(4); row["top"] = {str(k): int(v) for k, v in vc.items()}
        out.append(row)
    return out

def ds_info(name, df, target, source):
    task = testing.detect_task(df, target)
    d = {"name": name, "rows": int(len(df)), "cols": int(df.shape[1]), "source": source, "target": target, "task": task,
         "numeric": int(sum(pd.api.types.is_numeric_dtype(df[c]) for c in df.columns)),
         "missing_cells": int(df.isna().sum().sum()), "missing_pct": float(df.isna().sum().sum() / df.size * 100),
         "duplicates": int(df.duplicated().sum()), "columns": col_info(df, target)}
    if task == "classification":
        vc = df[target].value_counts(); d["classes"] = {str(k): int(v) for k, v in vc.items()}
    else:
        t = df[target]; d["target_stats"] = {k: float(v) for k, v in {"mean": t.mean(), "median": t.median(), "min": t.min(), "max": t.max(), "std": t.std(), "skew": t.skew()}.items()}
    return d

def slim(res):
    s = res["summary"]; m = res["metrics"]
    keep = {k: m[k] for k in m if k in ("task","accuracy","precision","recall","f1","train_f1","cv_mean","cv_std","r2","train_r2","rmse","mae","mape","confusion_matrix","classes","per_class","feature_importance","slices","comparison_table","scatter","fit_time")}
    return {"score": s["score"], "grade": s["grade"], "gate": s["gate"], "passed": s["passed"], "warned": s["warned"], "failed": s["failed"],
            "skipped": s["skipped"], "total": s["total"], "categories": s["categories"], "metrics": keep, "duration": res["duration_sec"],
            "tests": [{k: t[k] for k in ("id","name","category","status","value","threshold","details")} | {"data": t.get("data", {})} for t in res["tests"]],
            "model": res["config"]["model"]}

